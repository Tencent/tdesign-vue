import { mount } from '@vue/test-utils';
import { Select, OptionGroup, Option } from '@/src/select/index.ts';

describe('Select', () => {
  it('does not select an option after becoming disabled while open', async () => {
    const onChange = vi.fn();
    const wrapper = mount(Select, {
      attachTo: document.body,
      propsData: {
        defaultValue: 'Apple',
        defaultPopupVisible: true,
        options: ['Apple', 'Orange'].map((value) => ({ label: value, value })),
        onChange,
      },
    });

    const findOrange = () => Array.from(document.querySelectorAll('.t-select-option')).find(
      (option) => option.textContent.trim() === 'Orange',
    );
    await vi.waitFor(() => expect(findOrange()).toBeDefined());
    const orange = findOrange();
    await wrapper.setProps({ disabled: true });
    orange.click();

    expect(onChange).not.toHaveBeenCalled();
    expect(wrapper.find('input').element.value).toBe('Apple');

    await wrapper.setProps({ disabled: false });
    orange.click();
    expect(onChange).toHaveBeenCalledTimes(1);
    expect(onChange.mock.calls[0][0]).toBe('Orange');
    wrapper.destroy();
  });

  // test props api
  describe(':props', () => {
    it(':disabled', () => {
      const wrapper = mount({
        render() {
          return <Select disabled={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':size', () => {
      const wrapper = mount({
        render() {
          return <Select size="large"></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':clearable', () => {
      const wrapper = mount({
        render() {
          return <Select clearable={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':multiple', () => {
      const wrapper = mount({
        render() {
          return <Select multiple={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':placeholder', () => {
      const wrapper = mount({
        render() {
          return <Select placeholder="please select"></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':creatable', () => {
      const wrapper = mount({
        render() {
          return <Select creatable={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':remote', () => {
      const wrapper = mount({
        render() {
          return <Select remote={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':loading', () => {
      const wrapper = mount({
        render() {
          return <Select loading={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':labelInValue', () => {
      const wrapper = mount({
        render() {
          return <Select labelInValue={false}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':reserveKeyword', () => {
      const wrapper = mount({
        render() {
          return <Select reserveKeyword={false}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':bordered', () => {
      const wrapper = mount({
        render() {
          return <Select bordered={true}></Select>;
        },
      });
      expect(wrapper.element).toMatchSnapshot();
    });
    it(':filterable', async () => {
      const wrapper = mount(
        {
          render() {
            return <Select filterable={true}></Select>;
          },
        },
        { attachTo: document.body },
      );
      const input = wrapper.find('input[placeholder="请选择"]');
      input.trigger('focus');
      expect(input.element).toBe(document.activeElement);
    });
  });
});

